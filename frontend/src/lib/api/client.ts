import { ApiResponse } from "@/types/api";
import { AuthSession } from "@/features/auth/types/auth";

const API_BASE_URL =
  process.env.NEXT_PUBLIC_API_URL?.replace(/\/$/, "") ||
  "http://localhost:5050/api";

export const AUTH_STORAGE_KEY = "hrflow_auth_session";
export const AUTH_UPDATED_EVENT = "hrflow:auth-updated";
export const AUTH_LOGOUT_EVENT = "hrflow:auth-logout";

/**
 * In-memory (RAM) session store.
 * Keeps user profile/roles/permissions strictly in JavaScript heap memory (never written to localStorage).
 * Cleared automatically on page refresh (re-hydrated via /api/auth/me + HttpOnly Cookie) or tab close.
 */
let inMemorySession: AuthSession | null = null;

function purgeLegacyLocalStorage(): void {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.removeItem(AUTH_STORAGE_KEY);
    window.localStorage.removeItem("hrflow_last_activity_timestamp");
  } catch {
    // Ignore storage access errors
  }
}

export class ApiClientError extends Error {
  public readonly statusCode: number;
  public readonly errors?: string[] | null;

  constructor(message: string, statusCode: number, errors?: string[] | null) {
    super(message);
    this.name = "ApiClientError";
    this.statusCode = statusCode;
    this.errors = errors;
  }
}

/**
 * Extracts the Anti-CSRF token from the XSRF-TOKEN cookie generated by Backend.
 */
export function getXsrfToken(): string | null {
  if (typeof document === "undefined") return null;
  const match = document.cookie.match(/(^|;)\s*XSRF-TOKEN=([^;]+)/);
  return match ? decodeURIComponent(match[2]) : null;
}

/**
 * Reads user session stored strictly in RAM (in-memory state).
 * Never reads or writes sensitive role/permission metadata to localStorage.
 */
export function getStoredSession(): AuthSession | null {
  purgeLegacyLocalStorage();
  return inMemorySession;
}

/**
 * Saves sanitized session strictly in RAM (inMemorySession).
 * Guaranteed to never write to localStorage so DevTools -> Local Storage stays completely clean.
 */
export function setStoredSession(session: AuthSession | null): void {
  purgeLegacyLocalStorage();
  if (!session) {
    inMemorySession = null;
    return;
  }
  const { refreshToken: _unusedRefresh, accessToken: _unusedAccess, ...safeSession } = session;
  inMemorySession = safeSession as AuthSession;
}

export function getStoredAccessToken(): string | null {
  return getStoredSession()?.accessToken || null;
}

/**
 * Singleton refresh promise with mutex locking to prevent race conditions
 * when multiple concurrent requests receive 401 simultaneously.
 */
let refreshPromise: Promise<string | null> | null = null;

export async function tryRefreshAccessToken(): Promise<string | null> {
  if (typeof window === "undefined") return null;

  if (refreshPromise) {
    return refreshPromise;
  }

  refreshPromise = (async () => {
    try {
      // Backend reads HttpOnly refresh_token cookie automatically via credentials: "include"
      const session = getStoredSession();
      const response = await fetch(`${API_BASE_URL}/auth/refresh-token`, {
        method: "POST",
        credentials: "include",
        headers: {
          Accept: "application/json",
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          accessToken: session?.accessToken || "",
          refreshToken: "",
        }),
        cache: "no-store",
      });

      if (!response.ok) {
        setStoredSession(null);
        window.dispatchEvent(new CustomEvent(AUTH_LOGOUT_EVENT));
        return null;
      }

      const payload = (await response.json()) as ApiResponse<AuthSession>;
      if (!payload?.success || !payload.data) {
        setStoredSession(null);
        window.dispatchEvent(new CustomEvent(AUTH_LOGOUT_EVENT));
        return null;
      }

      setStoredSession(payload.data);
      window.dispatchEvent(
        new CustomEvent<AuthSession>(AUTH_UPDATED_EVENT, {
          detail: payload.data,
        })
      );

      return payload.data.accessToken || "cookie_session";
    } catch {
      return null;
    } finally {
      refreshPromise = null;
    }
  })();

  return refreshPromise;
}

/**
 * Checks whether the current access token has expired.
 * Supports both backend 'expiresAtUtc' and client 'accessTokenExpiresAt'.
 */
function isTokenExpired(session: AuthSession | null): boolean {
  const expiryStr = session?.expiresAtUtc || session?.accessTokenExpiresAt;
  if (!expiryStr) return false;
  const expiresMs = Date.parse(expiryStr);
  if (Number.isNaN(expiresMs)) return false;
  // Refresh 15 seconds before actual expiration to avoid edge 401s
  return Date.now() + 15_000 >= expiresMs;
}

/**
 * Builds a clean query string ignoring undefined, null, or empty string values.
 */
export function buildQueryString(params?: Record<string, unknown>): string {
  if (!params) return "";
  const searchParams = new URLSearchParams();

  Object.entries(params).forEach(([key, value]) => {
    if (value !== undefined && value !== null && String(value).trim() !== "") {
      searchParams.append(key, String(value).trim());
    }
  });

  const query = searchParams.toString();
  return query ? `?${query}` : "";
}

/**
 * Revokes current session on backend and clears local cookies & storage.
 */
export async function logoutApi(): Promise<void> {
  try {
    await fetch(`${API_BASE_URL}/auth/logout`, {
      method: "POST",
      credentials: "include",
      headers: {
        Accept: "application/json",
      },
      cache: "no-store",
    });
  } catch {
    // Ignore network error on logout
  } finally {
    setStoredSession(null);
    if (typeof window !== "undefined") {
      window.dispatchEvent(new CustomEvent(AUTH_LOGOUT_EVENT));
    }
  }
}

async function request<T>(
  method: string,
  endpoint: string,
  options?: {
    params?: Record<string, unknown>;
    body?: unknown;
    init?: RequestInit;
    _isRetry?: boolean;
  }
): Promise<T> {
  const path = endpoint.startsWith("/") ? endpoint : `/${endpoint}`;
  const url = `${API_BASE_URL}${path}${buildQueryString(options?.params)}`;
  const isAuthEndpoint =
    path.startsWith("/auth/login") ||
    path.startsWith("/auth/refresh-token") ||
    path.startsWith("/auth/logout");

  let session = getStoredSession();
  let token = session?.accessToken || null;

  // Proactively refresh if AccessToken has already expired
  if (!isAuthEndpoint && !options?._isRetry && isTokenExpired(session)) {
    const refreshedToken = await tryRefreshAccessToken();
    if (refreshedToken) {
      token = refreshedToken;
    }
  }

  const isMutatingMethod =
    ["POST", "PUT", "PATCH", "DELETE"].includes(method.toUpperCase());
  const xsrfToken = getXsrfToken();

  const headers: Record<string, string> = {
    Accept: "application/json",
    ...(options?.body !== undefined
      ? { "Content-Type": "application/json" }
      : {}),
    ...(token && token !== "cookie_session"
      ? { Authorization: `Bearer ${token}` }
      : {}),
    // Anti-CSRF protection header per SECURITY_HARDENING_RULES.md Rule #6
    ...(isMutatingMethod && !isAuthEndpoint && xsrfToken
      ? { "X-XSRF-TOKEN": xsrfToken }
      : {}),
    ...(options?.init?.headers as Record<string, string> | undefined),
  };

  const response = await fetch(url, {
    method,
    headers,
    credentials: "include", // Automatically send & receive HttpOnly Session Cookies
    body:
      options?.body !== undefined ? JSON.stringify(options.body) : undefined,
    cache: "no-store",
    ...options?.init,
  });

  // Automatically attempt Refresh Token once on HTTP 401
  if (response.status === 401 && !isAuthEndpoint && !options?._isRetry) {
    const newToken = await tryRefreshAccessToken();
    if (newToken) {
      return request<T>(method, endpoint, {
        ...options,
        _isRetry: true,
      });
    }
  }

  // Handle 204 No Content (e.g., DELETE /api/departments/{id})
  if (response.status === 204) {
    return true as unknown as T;
  }

  let payload: (ApiResponse<T> & { title?: string; detail?: string }) | null =
    null;
  try {
    payload = await response.json();
  } catch {
    throw new ApiClientError(
      `Không thể đọc phản hồi từ máy chủ (HTTP ${response.status}).`,
      response.status
    );
  }

  if (
    !response.ok ||
    !payload ||
    payload.success === false ||
    payload.data === null
  ) {
    let extractedErrors: string[] = [];
    if (Array.isArray(payload?.errors)) {
      extractedErrors = payload.errors.filter(Boolean);
    } else if (
      payload?.errors &&
      typeof payload.errors === "object" &&
      !Array.isArray(payload.errors)
    ) {
      extractedErrors = Object.values(
        payload.errors as Record<string, string[] | string>
      ).flatMap((item) => (Array.isArray(item) ? item : [item]));
    }

    const isGenericHttpError =
      extractedErrors.length === 1 &&
      (extractedErrors[0] === "Unauthorized (HTTP 401)." ||
        extractedErrors[0] === "Forbidden (HTTP 403).");

    const detailedError =
      !isGenericHttpError && extractedErrors.length > 0
        ? extractedErrors.join(" ")
        : payload?.message ||
          payload?.detail ||
          payload?.title ||
          extractedErrors[0] ||
          `Yêu cầu thất bại với mã trạng thái ${response.status}`;

    throw new ApiClientError(
      detailedError,
      response.status,
      extractedErrors.length > 0 ? extractedErrors : null
    );
  }

  return payload.data;
}

export async function apiGet<T>(
  endpoint: string,
  params?: Record<string, unknown>,
  init?: RequestInit
): Promise<T> {
  return request<T>("GET", endpoint, { params, init });
}

export async function apiPost<T>(
  endpoint: string,
  body?: unknown,
  init?: RequestInit
): Promise<T> {
  return request<T>("POST", endpoint, { body, init });
}

export async function apiPut<T>(
  endpoint: string,
  body?: unknown,
  init?: RequestInit
): Promise<T> {
  return request<T>("PUT", endpoint, { body, init });
}

export async function apiPatch<T>(
  endpoint: string,
  body?: unknown,
  init?: RequestInit
): Promise<T> {
  return request<T>("PATCH", endpoint, { body, init });
}

export async function apiDelete<T = boolean>(
  endpoint: string,
  body?: unknown,
  init?: RequestInit
): Promise<T> {
  return request<T>("DELETE", endpoint, { body, init });
}
